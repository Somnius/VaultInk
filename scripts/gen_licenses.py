#!/usr/bin/env python3
"""Write the open-source licence lists from docs/third-party.json.

    python3 scripts/gen_licenses.py            # write all three outputs
    python3 scripts/gen_licenses.py --md       # docs/licenses.md only
    python3 scripts/gen_licenses.py --header   # src/util/ThirdPartyData.h only
    python3 scripts/gen_licenses.py --notice   # the component list inside NOTICE only
    python3 scripts/gen_licenses.py --check    # write nothing; exit 1 if an output is out of date

docs/third-party.json is the only place to edit. Standard library only.
test/test_licenses.py checks that the outputs are up to date.
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_PATH = os.path.join(ROOT, "docs", "third-party.json")
MD_PATH = os.path.join(ROOT, "docs", "licenses.md")
HEADER_PATH = os.path.join(ROOT, "src", "util", "ThirdPartyData.h")
NOTICE_PATH = os.path.join(ROOT, "NOTICE")

# used_in value -> heading, in the order the lists are written.
GROUPS = [
    ("firmware", "Firmware"),
    ("device web pages", "Device web pages"),
    ("companion", "Companion app"),
    ("site", "Site (the loader page)"),
]
# The groups whose components are inside the firmware binary, so on the device's licence screen.
DEVICE_GROUPS = ("firmware", "device web pages")
NOT_VERIFIED = "not verified"
FIELDS = ("name", "version", "used_for", "licence", "copyright", "source", "used_in", "verified_from")
# The strings of the device table may not grow past this (bytes, each string with its NUL).
DEVICE_STRING_BUDGET = 6 * 1024

NOTICE_BEGIN = "Third-party code and assets in this repository keep their own licences:\n"
NOTICE_END = "See the licence files and headers inside each directory for the full terms.\n"
# NOTICE's wolfSSL statement, kept word for word.
NOTICE_WOLFSSL = (
    "- wolfSSL {version} (Arduino-wolfSSL, linked into the firmware for TLS 1.3 and the content code): "
    "GPL-2.0-or-later,\n"
    "  Copyright (c) wolfSSL Inc. wolfSSL is dual-licensed (GPL or a commercial licence). "
    "VaultInk uses it under the GPL.\n"
    "  Because of that, the firmware binaries are distributed under the terms of the GPL-2.0-or-later, with the\n"
    "  source in this repository. The source files of VaultInk itself stay under the MIT licence (see LICENSE).\n"
)


def load(path=JSON_PATH):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    known = {key for key, _ in GROUPS}
    names = set()
    for c in data["components"]:
        for field in FIELDS:
            if not isinstance(c.get(field), str):
                raise ValueError(f"{c.get('name', '?')}: missing field {field}")
        if c["used_in"] not in known:
            raise ValueError(f"{c['name']}: unknown used_in {c['used_in']!r}")
        if c["name"] in names:
            raise ValueError(f"{c['name']}: listed twice")
        names.add(c["name"])
        if not c["licence"]:
            raise ValueError(f"{c['name']}: empty licence (write '{NOT_VERIFIED}')")
        # A licence nobody read is not a licence: no source file, no licence name.
        if (c["licence"] == NOT_VERIFIED) != (c["verified_from"] == ""):
            raise ValueError(f"{c['name']}: 'not verified' and an empty verified_from go together")
    return data


def in_group(data, key):
    return [c for c in data["components"] if c["used_in"] == key]


def short_version(version):
    """The leading version number ('5.7.2 (wolfssl/...)' -> '5.7.2'), or '' when there is none."""
    m = re.match(r"\d[\w.]*", version)
    return m.group(0) if m else ""


# ---- docs/licenses.md ----


def md_cell(text):
    return text.replace("|", "\\|") if text else ""


def render_md(data):
    out = []
    out.append("# Open-source licences\n")
    out.append(
        "<!-- Generated by scripts/gen_licenses.py from docs/third-party.json. Do not edit this file: "
        "edit the JSON and run the script. -->\n"
    )
    out.append(
        "VaultInk's own code is under the MIT licence (see [LICENSE](../LICENSE)). The firmware binaries also "
        "contain wolfSSL, which is under the GPL-2.0-or-later, so the binaries are distributed under the terms "
        "of the GPL, with the source in this repository. Every other library, font and icon keeps its own "
        "licence, and that licence applies to it. They are all listed below.\n"
    )
    out.append("## What that means for you\n")
    out.append(
        "- You may use VaultInk, study how it works, change it and share it.\n"
        "- If you share the firmware binary, changed or not, you must also offer its source code under the "
        "same terms. The source is this repository: <https://github.com/Somnius/VaultInk>.\n"
        "- If you reuse one library from the list, follow that library's licence.\n"
        "- This page is not legal advice.\n"
    )
    out.append("## How this list is checked\n")
    out.append(
        "Each licence below was read from the library's own licence file, source header or package metadata; "
        "the last column names the file. Where no such file could be read, the licence says `not verified` "
        "instead of a guess. Paths that start with `.pio/`, `~/.platformio/` or `~/.gradle/` are the copies "
        "the build tools download; `freeink-sdk/` is a git submodule. The same list is on the device "
        "(Settings > System > About > Open-source licences), in [NOTICE](../NOTICE) and in the companion "
        "app's About screen.\n"
    )
    for key, heading in GROUPS:
        rows = in_group(data, key)
        if not rows:
            continue
        out.append(f"## {heading}\n")
        table = [
            "| Component | Version | Used for | Licence | Copyright | Source | Licence read from |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for c in rows:
            table.append(
                "| "
                + " | ".join(
                    md_cell(x)
                    for x in (
                        c["name"],
                        c["version"],
                        c["used_for"],
                        c["licence"],
                        c["copyright"],
                        f"<{c['source']}>" if c["source"] else "",
                        c["verified_from"],
                    )
                )
                + " |"
            )
        out.append("\n".join(table) + "\n")
        notes = [f"- **{c['name']}**: {c['notes']}" for c in rows if c.get("notes")]
        if notes:
            out.append("Notes:\n")
            out.append("\n".join(notes) + "\n")
    missing = [c for c in data["components"] if c["licence"] == NOT_VERIFIED]
    out.append("## Not verified\n")
    if missing:
        out.append("No licence file or package metadata was available for these, so their licence is not stated here:\n")
        out.append("\n".join(f"- {c['name']} ({c['used_in']}): <{c['source']}>" for c in missing) + "\n")
    else:
        out.append("Nothing: every licence above was read from a file.\n")
    out.append("## Not in this list\n")
    out.append(
        "- Tools that only run on the developer's computer and are not in any binary: GoogleTest (host tests), "
        "SDL2 (the simulator), Python and its packages (build scripts).\n"
        "- The libraries that the companion app's libraries pull in themselves (other AndroidX modules), apart "
        "from Okio.\n"
        "- The components inside ESP-IDF, as its note says.\n"
    )
    return "\n".join(out)


# ---- src/util/ThirdPartyData.h ----


def device_rows(data):
    rows = []
    for c in data["components"]:
        if c["used_in"] not in DEVICE_GROUPS or c.get("build_only"):
            continue
        version = short_version(c["version"])
        rows.append(
            (
                f"{c['name']} {version}" if version else c["name"],
                c["licence"],
                c["used_for"],
                re.sub(r"^https?://", "", c["source"]),
                c["copyright"],
            )
        )
    return rows


def device_string_bytes(rows):
    """Flash the strings take: identical literals are stored once, each with its NUL."""
    return sum(len(s.encode("utf-8")) + 1 for s in {s for row in rows for s in row})


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_header(data):
    rows = device_rows(data)
    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/gen_licenses.py from docs/third-party.json. Do not edit: edit the JSON and run",
        "// the script (test/test_licenses.py fails when this file is out of date).",
        "// The components inside the firmware binary, for Settings > System > About > Open-source licences.",
        "",
        "#include <cstddef>",
        "",
        "namespace thirdparty {",
        "",
        "struct Component {",
        "  const char* name;       // with the version when one is pinned",
        "  const char* licence;    // SPDX id, or \"not verified\"",
        "  const char* usedFor;    // English, like the names",
        "  const char* source;     // URL without the scheme",
        "  const char* copyright;  // \"\" when the licence file names none",
        "};",
        "",
        "// clang-format off",
        "inline constexpr Component COMPONENTS[] = {",
    ]
    for row in rows:
        lines.append("    {" + ", ".join(c_string(s) for s in row) + "},")
    lines += [
        "};",
        "// clang-format on",
        "",
        "inline constexpr size_t COMPONENT_COUNT = sizeof(COMPONENTS) / sizeof(COMPONENTS[0]);",
        "// Bytes of string data above (each string once, with its NUL); the table adds 20 bytes a row.",
        f"inline constexpr size_t STRING_BYTES = {device_string_bytes(rows)};",
        "",
        "}  // namespace thirdparty",
        "",
    ]
    return "\n".join(lines)


# ---- NOTICE ----


def notice_line(c):
    if c["name"] == "wolfSSL":
        return NOTICE_WOLFSSL.format(version=short_version(c["version"]))
    version = short_version(c["version"])
    head = f"- {c['name']}{' ' + version if version else ''} ({c['used_for']}): {c['licence']}"
    if c["copyright"]:
        head += f", {c['copyright']}"
    return head.rstrip(".") + ".\n"


def render_notice_block(data):
    parts = [NOTICE_BEGIN]
    for key, heading in GROUPS:
        rows = in_group(data, key)
        if not rows:
            continue
        parts.append(f"\n{heading}:\n\n")
        parts.extend(notice_line(c) for c in rows)
    parts.append(
        "\n'not verified' means no licence file was available to read. The full table, with the file each\n"
        "licence was read from, is in docs/licenses.md.\n\n"
    )
    return "".join(parts)


def render_notice(data, current):
    start = current.index(NOTICE_BEGIN)
    end = current.index(NOTICE_END)
    return current[:start] + render_notice_block(data) + current[end:]


# ---- main ----


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def outputs(data):
    """(path, wanted text) for every generated file."""
    return {
        "md": (MD_PATH, render_md(data)),
        "header": (HEADER_PATH, render_header(data)),
        "notice": (NOTICE_PATH, render_notice(data, read(NOTICE_PATH))),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--md", action="store_true", help="write docs/licenses.md")
    parser.add_argument("--header", action="store_true", help="write src/util/ThirdPartyData.h")
    parser.add_argument("--notice", action="store_true", help="write the component list in NOTICE")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if an output is out of date")
    args = parser.parse_args(argv)

    data = load()
    rows = device_rows(data)
    size = device_string_bytes(rows)
    if size > DEVICE_STRING_BUDGET:
        print(f"device strings are {size} bytes, over the {DEVICE_STRING_BUDGET} budget", file=sys.stderr)
        return 1

    wanted = [k for k in ("md", "header", "notice") if getattr(args, k)] or ["md", "header", "notice"]
    stale = 0
    for key in wanted:
        path, text = outputs(data)[key]
        rel = os.path.relpath(path, ROOT)
        current = read(path) if os.path.exists(path) else None
        if current == text:
            continue
        if args.check:
            print(f"out of date: {rel} (run python3 scripts/gen_licenses.py)", file=sys.stderr)
            stale += 1
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {rel}")
    if not args.check:
        print(f"{len(data['components'])} components; {len(rows)} on the device, {size} bytes of strings")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
