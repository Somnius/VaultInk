#!/usr/bin/env python3
"""Writes lib/Ssh/SshTermFontData.cpp: the SSH terminal's fixed-cell 1-bit font.

The glyphs come from the BDF files of Terminus Font (SIL Open Font License 1.1, the licence text is
lib/Ssh/fonts/OFL.TXT). The output is a subset in another format, so under the licence it is a
Modified Version and does not carry the reserved name: the firmware calls it the terminal font.

Usage:
  python3 scripts/gen_ssh_font.py <folder with ter-u12n.bdf ter-u14n.bdf ter-u16n.bdf ter-u18n.bdf>

The folder is the unpacked terminus-font-4.49.1.tar.gz (lib/Ssh/fonts/README.md names the download
and its checksum). Every size must hold the same characters: one code point table serves them all.
"""

import os
import re
import sys

SIZES = (12, 14, 16, 18)  # cell heights; the widths are 6, 8, 8 and 10
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "Ssh", "SshTermFontData.cpp")


def wanted(cp):
    """Left out: NUL, combining marks (the terminal has no zero-width cells), Hebrew (no
    right-to-left in the terminal), Braille patterns (256 glyphs used by full-screen programs,
    which the terminal does not run) and the private-use glyphs."""
    if cp < 0x20:
        return False
    if 0x300 <= cp <= 0x36F or 0x5D0 <= cp <= 0x5EA or 0x2800 <= cp <= 0x28FF:
        return False
    if 0xE000 <= cp <= 0xF8FF:
        return False
    return cp <= 0xFFFF


def read_bdf(path):
    """{code point: [row bits as int, left aligned in the cell width]}, cell width, cell height."""
    text = open(path, encoding="latin-1").read()
    box = re.search(r"^FONTBOUNDINGBOX (\d+) (\d+) (-?\d+) (-?\d+)", text, re.M)
    width, height = int(box.group(1)), int(box.group(2))
    glyphs = {}
    for block in text.split("STARTCHAR")[1:]:
        cp = int(re.search(r"^ENCODING (-?\d+)", block, re.M).group(1))
        bbx = [int(v) for v in re.search(r"^BBX (\d+) (\d+) (-?\d+) (-?\d+)", block, re.M).groups()]
        if bbx[0] != width or bbx[1] != height:
            raise SystemExit("%s: U+%04X is not a full cell (%r)" % (path, cp, bbx))
        rows = re.search(r"^BITMAP\n(.*?)^ENDCHAR", block, re.M | re.S).group(1).split()
        if len(rows) != height:
            raise SystemExit("%s: U+%04X has %d rows" % (path, cp, len(rows)))
        row_bytes = (width + 7) // 8
        bits = []
        for row in rows:
            value = int(row, 16) >> (len(row) * 4 - row_bytes * 8)
            bits.append(value)
        glyphs[cp] = bits
    return glyphs, width, height


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    fonts = [read_bdf(os.path.join(sys.argv[1], "ter-u%dn.bdf" % size)) for size in SIZES]
    cps = sorted(cp for cp in fonts[0][0] if wanted(cp))
    for glyphs, _, height in fonts:
        if sorted(cp for cp in glyphs if wanted(cp)) != cps:
            raise SystemExit("size %d holds other characters" % height)

    out = []
    out.append("// Generated by scripts/gen_ssh_font.py from Terminus Font 4.49.1 (ter-u12n, ter-u14n, ter-u16n,")
    out.append("// ter-u18n). Copyright (C) 2020 Dimitar Toshkov Zhekov. SIL Open Font License 1.1:")
    out.append("// lib/Ssh/fonts/OFL.TXT. A subset in another format, so not under the reserved font name.")
    out.append("// Do not edit; run the script again.")
    out.append('#include "SshTermFont.h"')
    out.append("")
    out.append("namespace sshfont {")
    out.append("namespace data {")
    out.append("")
    out.append("extern const uint16_t GLYPH_COUNT = %d;" % len(cps))
    out.append("extern const uint16_t CODEPOINTS[] = {")
    for i in range(0, len(cps), 12):
        out.append("    " + ", ".join("0x%04X" % cp for cp in cps[i : i + 12]) + ",")
    out.append("};")
    total = len(cps) * 2
    for glyphs, width, height in fonts:
        row_bytes = (width + 7) // 8
        out.append("")
        out.append("// %d x %d cells, %d byte(s) a row, the first column in the top bit." % (width, height, row_bytes))
        out.append("extern const uint8_t ROWS_%d[] = {" % height)
        for cp in cps:
            data = []
            for value in glyphs[cp]:
                for shift in range(row_bytes - 1, -1, -1):
                    data.append((value >> (shift * 8)) & 0xFF)
            total += len(data)
            out.append("    " + ",".join("0x%02X" % b for b in data) + ",  // U+%04X" % cp)
        out.append("};")
    out.append("")
    out.append("}  // namespace data")
    out.append("}  // namespace sshfont")
    with open(OUT, "w", encoding="ascii") as handle:
        handle.write("\n".join(out) + "\n")
    print("%d glyphs, %d bytes of font data -> %s" % (len(cps), total, os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
