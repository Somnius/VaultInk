#!/bin/bash
# Writes src/util/CaBundle.h: the root certificates VaultInk trusts for HTTPS by default, taken
# from the system's Mozilla CA store (/etc/ssl/certs). Run it again to refresh them.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOTS=(ISRG_Root_X1 ISRG_Root_X2 DigiCert_Global_Root_G2 GTS_Root_R1 GTS_Root_R4 Amazon_Root_CA_1
       USERTrust_RSA_Certification_Authority)
OUT=src/util/CaBundle.h
{
  echo "#pragma once"
  echo
  echo "// Generated by scripts/gen_ca_bundle.sh from the Mozilla CA store. Do not edit."
  echo "// Let's Encrypt (ISRG X1, X2), DigiCert G2, Google Trust Services (R1, R4, Cloudflare too),"
  echo "// Amazon, Sectigo/USERTrust: the roots behind most self-hosted and cloud CouchDB servers."
  echo "namespace ca_bundle {"
  echo "inline constexpr const char PEM[] ="
  for r in "${ROOTS[@]}"; do
    echo "    // $(openssl x509 -in "/etc/ssl/certs/$r.pem" -noout -subject | sed 's/^subject=//')"
    echo "    // SHA-256 $(openssl x509 -in "/etc/ssl/certs/$r.pem" -noout -fingerprint -sha256 | cut -d= -f2)"
    openssl x509 -in "/etc/ssl/certs/$r.pem" | sed 's/.*/    "&\\n"/'
  done
  echo "    ;"
  echo "}  // namespace ca_bundle"
} > "$OUT"
echo "Wrote $OUT ($(wc -c < "$OUT") bytes)"
