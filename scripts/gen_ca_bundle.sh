#!/bin/bash
# Writes lib/TlsPolicy/CaBundle.h: the root certificates VaultInk trusts for HTTPS by default, taken
# from the system's Mozilla CA store (/etc/ssl/certs). Run it again to refresh them.
#
# Two groups, in one string so the second costs no extra flash:
#   SELF_HOSTED  roots only a server of your own is likely to use
#   PUBLIC       roots behind the hosts the firmware itself talks to (GitHub, Wikipedia)
# ca_bundle::PEM is both; ca_bundle::publicPem() is the tail of the same string, so a connection to
# GitHub or Wikipedia parses half as many certificates into the heap.
#
# Chains read with `openssl s_client -showcerts` on 2026-11-10:
#   *.wikipedia.org                  Let's Encrypt YE2 -> ISRG Root YE -> ISRG Root X2 -> ISRG Root X1
#   github.com, api.github.com       Sectigo DV E36 -> Sectigo Root E46 -> USERTrust ECC
#   release-assets / objects.githubusercontent.com
#                                    Let's Encrypt YR1 -> ISRG Root YR -> ISRG Root X1
# GlobalSign Root R3 is kept for Wikimedia; no chain read that day used it.
set -euo pipefail
cd "$(dirname "$0")/.."
SELF_HOSTED=(DigiCert_Global_Root_G2 GTS_Root_R1 GTS_Root_R4 Amazon_Root_CA_1
             USERTrust_RSA_Certification_Authority)
PUBLIC=(ISRG_Root_X1 ISRG_Root_X2 USERTrust_ECC_Certification_Authority
        Sectigo_Public_Server_Authentication_Root_E46 GlobalSign_Root_CA_-_R3)
OUT=lib/TlsPolicy/CaBundle.h

emit_group() {
  local name=$1
  shift
  echo "#define VAULTINK_CA_$name \\"
  for r in "$@"; do
    echo "  /* $(openssl x509 -in "/etc/ssl/certs/$r.pem" -noout -subject | sed 's/^subject=//') */ \\"
    echo "  /* SHA-256 $(openssl x509 -in "/etc/ssl/certs/$r.pem" -noout -fingerprint -sha256 | cut -d= -f2) */ \\"
    openssl x509 -in "/etc/ssl/certs/$r.pem" | sed 's/.*/  "&\\n" \\/'
  done
  echo '  ""'
}

{
  echo "#pragma once"
  echo
  echo "// Generated by scripts/gen_ca_bundle.sh from the Mozilla CA store. Do not edit."
  echo "// Self-hosted group: DigiCert G2, Google Trust Services (R1, R4, Cloudflare too), Amazon,"
  echo "// Sectigo/USERTrust RSA. Public group: Let's Encrypt (ISRG X1, X2), USERTrust ECC and Sectigo"
  echo "// E46 (GitHub), GlobalSign R3: the hosts the firmware itself talks to, and most servers of"
  echo "// your own too."
  echo "// clang-format off"
  emit_group SELF_HOSTED "${SELF_HOSTED[@]}"
  echo
  emit_group PUBLIC "${PUBLIC[@]}"
  echo "// clang-format on"
  echo
  echo "namespace ca_bundle {"
  echo "// Every root, for a server the user set up."
  echo "inline constexpr const char PEM[] = VAULTINK_CA_SELF_HOSTED VAULTINK_CA_PUBLIC;"
  echo "// Only the public group: the tail of PEM, so it is not stored twice."
  echo "inline constexpr const char* publicPem() { return PEM + (sizeof(VAULTINK_CA_SELF_HOSTED) - 1); }"
  echo "}  // namespace ca_bundle"
  echo
  echo "#undef VAULTINK_CA_SELF_HOSTED"
  echo "#undef VAULTINK_CA_PUBLIC"
} > "$OUT"
echo "Wrote $OUT ($(wc -c < "$OUT") bytes)"
