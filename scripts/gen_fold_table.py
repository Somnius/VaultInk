#!/usr/bin/env python3
"""Generate lib/Vault/FoldTable.h: codepoint -> search-folded codepoint (lower case, no accents).

Covers Latin-1/Latin Extended-A/B, Greek and Coptic, Greek Extended (polytonic) and Cyrillic.
Final sigma folds to sigma. Run: python3 scripts/gen_fold_table.py > lib/Vault/FoldTable.h
"""
import sys
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x04FF), (0x1F00, 0x1FFF)]


def fold(cp):
    ch = chr(cp)
    base = unicodedata.normalize("NFD", ch)[0]
    low = base.lower()
    if len(low) != 1:
        return None
    if low == "ς":  # final sigma
        low = "σ"
    if not unicodedata.category(low).startswith("L"):
        return None
    return ord(low)


pairs = []
for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        try:
            unicodedata.name(chr(cp))
        except ValueError:
            continue
        f = fold(cp)
        if f is not None and f != cp:
            pairs.append((cp, f))
# Upper-case ASCII is handled in code; final sigma is in range above.

out = sys.stdout
out.write("#pragma once\n\n// Generated by scripts/gen_fold_table.py (Python %s, Unicode %s). Do not edit.\n"
          % (sys.version.split()[0], unicodedata.unidata_version))
out.write("// Sorted pairs: {codepoint, folded codepoint}.\n\n#include <cstdint>\n\n")
out.write("namespace foldtable {\nstruct Pair {\n  uint16_t from;\n  uint16_t to;\n};\n")
out.write("constexpr Pair PAIRS[] = {\n")
for i in range(0, len(pairs), 6):
    out.write("    " + " ".join("{0x%04X, 0x%04X}," % p for p in pairs[i:i + 6]) + "\n")
out.write("};\n}  // namespace foldtable\n")
