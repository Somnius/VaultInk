# Puts the newest entries of CHANGELOG.md into the firmware (src/util/ChangelogData.generated.h),
# for the "What's new" note shown once after an update.
from pathlib import Path
import re

try:
    Import("env")  # noqa: F821 (PlatformIO)
    ROOT = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    ROOT = Path(__file__).resolve().parent.parent

KEEP = 12  # releases carried in the firmware
src = ROOT / "CHANGELOG.md"
text = src.read_text(encoding="utf-8") if src.exists() else ""
entries = []
for match in re.finditer(r"^## (\d+\.\d+\.\d+) \(([^)]*)\)\n(.*?)(?=^## |\Z)", text, re.S | re.M):
    entries.append((match.group(1), match.group(2), match.group(3).strip()))
entries = entries[:KEEP]


def c_string(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + out + '"'


lines = [
    "// THIS FILE IS AUTOGENERATED by scripts/embed_changelog.py from CHANGELOG.md, DO NOT EDIT",
    "#pragma once",
    "",
    "namespace changelog_data {",
    "struct Entry {",
    "  const char* version;",
    "  const char* date;",
    "  const char* text;",
    "};",
    "inline constexpr Entry ENTRIES[] = {",
]
for version, date, body in entries:
    lines.append(f"    {{{c_string(version)}, {c_string(date)}, {c_string(body)}}},")
if not entries:
    lines.append('    {"0.0.0", "", ""},')
lines += ["};", f"inline constexpr int COUNT = {max(len(entries), 1)};", "}  // namespace changelog_data", ""]
out = ROOT / "src" / "util" / "ChangelogData.generated.h"
new = "\n".join(lines)
if not out.exists() or out.read_text(encoding="utf-8") != new:
    out.write_text(new, encoding="utf-8")
print(f"Changelog: {len(entries)} releases embedded")
